# 3. Orient — detector x/y onto scan x/y
# ─────────────────────────────────────────────────────────────────────────────

def rotate_shifts(shifts: np.ndarray, angle_deg: float, *,
                  flip: bool = False, reverse: bool = False) -> np.ndarray:
    """Put the beam-shift vectors into the scan frame.

    Three corrections, applied in this order, because that is the order the
    instrument applies them in reverse:

    *flip* swaps the x and y components — a HANDEDNESS change, for when the scan
    coils and the detector read out with opposite chirality. It has to come
    first: a mirror does not commute with a rotation, and doing it afterwards
    silently negates the fitted angle.

    *angle_deg* rotates the vectors CLOCKWISE, matching pyxem's
    ``rotate_beam_shifts`` exactly (same formula, so a SpyDE angle and a pyxem
    angle mean the same thing).

    *reverse* adds 180°, for the sign ambiguity :func:`estimate_rotation`
    cannot resolve on its own.
    """
    s = np.asarray(shifts, dtype=np.float64)
    sx, sy = s[..., 0], s[..., 1]
    if flip:
        sx, sy = sy, sx
    ang = np.deg2rad(float(angle_deg) + (180.0 if reverse else 0.0))
    c, sn = np.cos(ang), np.sin(ang)
    return np.stack([sx * c - sy * sn, sx * sn + sy * c], axis=-1)


def _div_curl(sx: np.ndarray, sy: np.ndarray,
              scale: tuple[float, float] = (1.0, 1.0)
              ) -> tuple[np.ndarray, np.ndarray]:
    """``(divergence, curl_z)`` of the in-plane field, in SCAN coordinates.

    Axis 0 of the arrays is the scan's y (rows), axis 1 its x (columns).
    *scale* is ``(dy, dx)`` in whatever calibrated unit the nav axes use; it
    cancels out of the rotation search (both terms scale together) but keeps the
    reported numbers physical.
    """
    dy, dx = float(scale[0]) or 1.0, float(scale[1]) or 1.0
    dsx_dy, dsx_dx = np.gradient(sx, dy, dx)
    dsy_dy, dsy_dx = np.gradient(sy, dy, dx)
    return dsx_dx + dsy_dy, dsy_dx - dsx_dy


def _rms(a: np.ndarray) -> float:
    finite = a[np.isfinite(a)]
    return float(np.sqrt(np.mean(finite ** 2))) if finite.size else 0.0


@dataclass
class RotationEstimate:
    """The result of :func:`estimate_rotation`."""
    angle: float                     #: best clockwise rotation, degrees
    flip: bool                       #: whether swapping x/y won
    mode: str                        #: "electric" (min curl) or "magnetic" (min div)
    score: float                     #: the minimised RMS at *angle*
    baseline: float                  #: the same RMS at 0°, no flip
    angles: np.ndarray = _dc_field(default_factory=lambda: np.empty(0))
    curve: np.ndarray = _dc_field(default_factory=lambda: np.empty(0))

    @property
    def improvement(self) -> float:
        """How many times smaller the residual got. 1.0 = the fit found nothing."""
        return float(self.baseline / self.score) if self.score > 0 else float("inf")

    def as_dict(self) -> dict:
        return {"angle": float(self.angle), "flip": bool(self.flip),
                "mode": self.mode, "score": float(self.score),
                "baseline": float(self.baseline),
                "improvement": float(min(self.improvement, 1e6))}


def estimate_rotation(shifts: np.ndarray, *, mode: str = "electric",
                      nav_scale: tuple[float, float] = (1.0, 1.0),
                      step_deg: float = 0.5) -> RotationEstimate:
    """Find the scan↔detector rotation (and handedness) from the data itself.

    The physics gives one constraint per mode:

    * **electric** — ``E = −∇V`` is a gradient field, so its curl vanishes.
    * **magnetic** — the Lorentz deflection is ``∝ B × ẑ``; with ``∇·B = 0`` in
      a uniform-thickness film the in-plane shift field is divergence-free.

    So the correct rotation is the one that drives the wrong-symmetry component
    to zero. The search is closed-form rather than brute force: rotating the
    vectors by θ takes ``(div, curl)`` to

        ``div(θ)  =  cos θ · div₀ − sin θ · curl₀``
        ``curl(θ) =  sin θ · div₀ + cos θ · curl₀``

    so ``div₀`` and ``curl₀`` are differentiated ONCE and the whole θ sweep is a
    pair of dot products. Both handedness options are evaluated and the better
    one returned.

    **180° is not resolvable this way** — both residuals are even under
    ``θ → θ + 180`` — which is why :func:`rotate_shifts` takes a separate
    ``reverse`` flag for the user to set from physical knowledge (which side of
    a p-n junction is positive, which way the domains point).
    """
    if mode not in FIELD_MODES:
        raise ValueError(f"mode must be one of {FIELD_MODES}, got {mode!r}")
    s = np.asarray(shifts, dtype=np.float64)
    angles = np.arange(0.0, 360.0, float(step_deg))
    rad = np.deg2rad(angles)
    cos_t, sin_t = np.cos(rad), np.sin(rad)

    best: RotationEstimate | None = None
    baseline = 0.0
    for flip in (False, True):
        sx, sy = (s[..., 1], s[..., 0]) if flip else (s[..., 0], s[..., 1])
        div0, curl0 = _div_curl(sx, sy, nav_scale)
        d0, c0 = div0.ravel(), curl0.ravel()
        good = np.isfinite(d0) & np.isfinite(c0)
        d0, c0 = d0[good], c0[good]
        if d0.size == 0:                                     # pragma: no cover
            continue
        # ⟨(a·d0 + b·c0)²⟩ expands to a²⟨d0²⟩ + 2ab⟨d0c0⟩ + b²⟨c0²⟩, so the
        # whole sweep needs three scalars — not one gradient per angle.
        dd, dc, cc = float(d0 @ d0), float(d0 @ c0), float(c0 @ c0)
        n = float(d0.size)
        if mode == "electric":            # minimise curl(θ)
            a, b = sin_t, cos_t
        else:                             # minimise div(θ)
            a, b = cos_t, -sin_t
        curve = np.sqrt(np.maximum(0.0, (a * a * dd + 2 * a * b * dc
                                         + b * b * cc) / n))
        if not flip:
            baseline = float(curve[0])
        i = int(np.argmin(curve))
        cand = RotationEstimate(angle=float(angles[i]), flip=flip, mode=mode,
                                score=float(curve[i]), baseline=baseline,
                                angles=angles, curve=curve)
        if best is None or cand.score < best.score:
            best = cand
    if best is None:                                         # pragma: no cover
        return RotationEstimate(angle=0.0, flip=False, mode=mode, score=0.0,
                                baseline=0.0, angles=angles,
                                curve=np.zeros_like(angles))
    best.baseline = baseline
    return best


def field_symmetry(shifts: np.ndarray,
                   nav_scale: tuple[float, float] = (1.0, 1.0)
                   ) -> tuple[float, float]:
    """``(rms_divergence, rms_curl)`` of a field — the rotation quality readout."""
    s = np.asarray(shifts, dtype=np.float64)
    div, curl = _div_curl(s[..., 0], s[..., 1], nav_scale)
    return _rms(div), _rms(curl)


