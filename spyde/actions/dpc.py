def corner_slices(nav_shape: tuple[int, int],
                  corner_fraction: float = DEFAULT_CORNER_FRACTION
                  ) -> list[tuple[slice, slice]]:
    """The four corner blocks of a scan as ``(row_slice, col_slice)`` pairs.

    *nav_shape* is ``(ny, nx)`` — numpy order, matching ``shifts[..., 0].shape``.
    Each block spans ``corner_fraction`` of ITS OWN axis, so a 512 × 64 scan gets
    boxes that are wide and short rather than square.

    That last point is a deliberate divergence from pyxem's
    ``_get_corner_slices``, which derives both block sizes from
    ``navigation_axes[0]``/``[1]`` and then applies them to the numpy array in
    the opposite order — harmless on a square scan, transposed on any other. We
    build the mask ourselves and hand it to ``get_linear_plane(mask=…)`` instead
    of using ``fit_corners=…``, so the boxes the user SEES on the navigator are
    exactly the pixels the plane is fitted to (``test_dpc.py`` pins that).
    """
    ny, nx = int(nav_shape[0]), int(nav_shape[1])
    frac = float(np.clip(corner_fraction, 1e-6, 0.5))
    # Floor each side at MIN_CORNER_PX. Two planes of three parameters need 6
    # points; 1x1 boxes give exactly 4, so the fit is under-determined and the
    # blocks are invisible on screen besides. On a 256-wide scan the default 5%
    # is 13 px and the floor never binds — it exists for the small scans where
    # a fraction alone degenerates.
    hy = int(max(MIN_CORNER_PX, min(ny, round(ny * frac))))
    hx = int(max(MIN_CORNER_PX, min(nx, round(nx * frac))))
    top, bottom = slice(0, hy), slice(ny - hy, ny)
    left, right = slice(0, hx), slice(nx - hx, nx)
    return [(top, left), (top, right), (bottom, left), (bottom, right)]


def corner_boxes(nav_shape: tuple[int, int],
                 corner_fraction: float = DEFAULT_CORNER_FRACTION
                 ) -> list[tuple[float, float, float, float]]:
    """The same four blocks as drawable ``(x, y, w, h)`` rectangles.

    IMAGE PIXELS, the frame anyplotlib's 2-D widgets and markers use (see
    ``drift_action`` — do not add a scale conversion). Same source as
    :func:`corner_slices`, so the overlay cannot disagree with the fit.
    """
    out = []
    for rs, cs in corner_slices(nav_shape, corner_fraction):
        out.append((float(cs.start), float(rs.start),
                    float(cs.stop - cs.start), float(rs.stop - rs.start)))
    return out


def corner_mask(nav_shape: tuple[int, int],
                corner_fraction: float = DEFAULT_CORNER_FRACTION) -> np.ndarray:
    """``get_linear_plane``-style mask: ``True`` where the fit must IGNORE.

    So it is ``True`` everywhere except inside the four corner blocks.
    """
    mask = np.ones((int(nav_shape[0]), int(nav_shape[1])), dtype=bool)
    for rs, cs in corner_slices(nav_shape, corner_fraction):
        mask[rs, cs] = False
    return mask


def _fit_plane(values: np.ndarray, mask: np.ndarray | None) -> np.ndarray:
    """Least-squares plane ``a·col + b·row + c`` through the UNMASKED points.

    *mask* is ``True`` = ignore (pyxem's polarity). Falls back to the masked
    mean, then to zeros, when the selected points can't determine a plane
    (fewer than 3, or all collinear) — a flat reference is a defensible
    reference; a singular-matrix traceback in the middle of a wizard is not.
    """
    ny, nx = values.shape
    rows, cols = np.mgrid[0:ny, 0:nx]
    keep = np.isfinite(values)
    if mask is not None:
        keep &= ~mask
    n = int(keep.sum())
    if n == 0:
        return np.zeros_like(values, dtype=np.float64)
    A = np.stack([cols[keep].ravel(), rows[keep].ravel(),
                  np.ones(n)], axis=1).astype(np.float64)
    b = values[keep].ravel().astype(np.float64)
    if n < 3:
        return np.full_like(values, float(b.mean()), dtype=np.float64)
    try:
        coef, *_ = np.linalg.lstsq(A, b, rcond=None)
    except np.linalg.LinAlgError:                            # pragma: no cover
        return np.full_like(values, float(b.mean()), dtype=np.float64)
    if not np.all(np.isfinite(coef)):                        # pragma: no cover
        return np.full_like(values, float(b.mean()), dtype=np.float64)
    return (coef[0] * cols + coef[1] * rows + coef[2]).astype(np.float64)


def plane_through(shifts: np.ndarray, mask: np.ndarray | None) -> np.ndarray:
    """Fit an independent plane to each of the x- and y-shift components."""
    shifts = np.asarray(shifts, dtype=np.float64)
    return np.stack([_fit_plane(shifts[..., 0], mask),
                     _fit_plane(shifts[..., 1], mask)], axis=-1)


def corner_reference(shifts: np.ndarray,
                     corner_fraction: float = DEFAULT_CORNER_FRACTION
                     ) -> np.ndarray:
    """Descan reference from the four scan corners.

    The corners are assumed to be off the feature of interest, so whatever beam
    shift they carry is instrument descan. A plane through them extrapolates
    that ramp across the whole scan — pyxem's ``get_linear_plane(fit_corners=…)``
    idea, with the boxes made visible and made correct on non-square scans (see
    :func:`corner_slices`).
    """
    nav_shape = np.asarray(shifts).shape[:2]
    return plane_through(shifts, corner_mask(nav_shape, corner_fraction))


def constant_reference(nav_shape: tuple[int, int], center_xy, sig_shape
                       ) -> np.ndarray:
    """Descan reference from ONE hand-picked beam position (the Manual tab).

    *center_xy* is the picked ``(x, y)`` in detector pixels; *sig_shape* is
    ``(sy, sx)``. The result is the constant ``centre − picked``, broadcast over
    the scan — the same value and the same sign convention
    ``get_direct_beam_position`` would have produced if the beam sat exactly
    there in every pattern.
    """
    sy, sx = int(sig_shape[0]), int(sig_shape[1])
    ref = np.zeros((int(nav_shape[0]), int(nav_shape[1]), 2), dtype=np.float64)
    ref[..., 0] = sx / 2.0 - float(center_xy[0])
    ref[..., 1] = sy / 2.0 - float(center_xy[1])
    return ref


def vacuum_reference(shifts: np.ndarray, vacuum_shifts: np.ndarray, *,
                     smooth: bool = True) -> np.ndarray:
    """Descan reference from a VACUUM scan taken with the same scan settings.

    The gold standard: the vacuum scan contains only the instrument's descan, so
    it is subtracted point for point.

    *smooth* (the default) reduces the vacuum field to its own fitted plane
    first, which is usually what you want — it keeps the vacuum scan's shot
    noise out of the sample's field, and the descan being corrected for really
    is a plane. Set it False to subtract the vacuum scan verbatim.

    **A differently-shaped vacuum scan is assumed to cover the SAME FIELD OF
    VIEW at a different sampling density** — the plane is re-evaluated on the
    sample's grid in normalised corner-to-corner coordinates. That is the real
    case this handles (a quick coarse vacuum scan before a fine sample scan),
    but it is an assumption the array shapes cannot confirm: a vacuum scan of a
    DIFFERENT field of view gets its ramp stretched or squashed to fit, and the
    result is wrong in a way that still looks plausible. The caller is expected
    to say so — ``dpc_action`` warns in the status line whenever the shapes
    differ. Matching shapes need no such assumption and are always preferred.
    """
    shifts = np.asarray(shifts, dtype=np.float64)
    vac = np.asarray(vacuum_shifts, dtype=np.float64)
    if vac.ndim != 3 or vac.shape[-1] != 2:
        raise ValueError(
            f"vacuum reference must be an (ny, nx, 2) beam-shift field, got "
            f"{vac.shape}")
    if vac.shape[:2] == shifts.shape[:2] and not smooth:
        return vac
    plane = plane_through(vac, None)
    if plane.shape[:2] == shifts.shape[:2]:
        return plane
    return _resample_plane(plane, shifts.shape[:2])


def _resample_plane(plane: np.ndarray, nav_shape: tuple[int, int]) -> np.ndarray:
    """Re-evaluate a fitted plane on a different-sized scan grid.

    A plane is fully described by its corners, so bilinear interpolation between
    them is exact — no scipy, no resampling artefacts.
    """
    ny, nx = int(nav_shape[0]), int(nav_shape[1])
    sy, sx = plane.shape[0], plane.shape[1]
    v = np.linspace(0.0, 1.0, ny)[:, None]
    u = np.linspace(0.0, 1.0, nx)[None, :]
    out = np.empty((ny, nx, 2), dtype=np.float64)
    for c in (0, 1):
        p = plane[..., c]
        tl, tr = p[0, 0], p[0, sx - 1]
        bl, br = p[sy - 1, 0], p[sy - 1, sx - 1]
        out[..., c] = (tl * (1 - u) * (1 - v) + tr * u * (1 - v)
                       + bl * (1 - u) * v + br * u * v)
    return out


@dataclass
class CenteringReport:
    """What is left of the beam-shift field once the sample signal is set aside.

    ``offset`` is the scan-mean shift (a constant descan) and ``ramp`` the
    peak-to-peak of the fitted plane across the scan (a descan gradient), both
    in detector pixels as ``(x, y)``. :attr:`centered` is the wizard's
    "there is nothing to correct here, skip this step" verdict.
    """
    offset: tuple[float, float]
    ramp: tuple[float, float]
    tol_px: float

    @property
    def worst(self) -> float:
        return float(max(max(abs(v) for v in self.offset),
                         max(abs(v) for v in self.ramp)))

    @property
    def centered(self) -> bool:
        return self.worst <= self.tol_px

    def as_dict(self) -> dict:
        return {"offset": list(self.offset), "ramp": list(self.ramp),
                "worst": self.worst, "centered": self.centered,
                "tol_px": self.tol_px}


def centering_report(shifts: np.ndarray, *, tol_px: float = CENTERED_TOL_PX
                     ) -> CenteringReport:
    """Measure the residual descan so the Center step can be skipped honestly.

    Both parts matter and neither alone is enough: a scan can be perfectly
    centred on average while carrying a large ramp, and it can have zero ramp
    while sitting a long way off centre. A dataset that is already centered
    (e.g. Center Zero Beam has run, or the microscope descan was good) shows
    small values for both, and the wizard says so instead of making the user
    guess.
    """
    shifts = np.asarray(shifts, dtype=np.float64)
    plane = plane_through(shifts, None)
    offs, ramps = [], []
    for c in (0, 1):
        v = shifts[..., c]
        finite = v[np.isfinite(v)]
        offs.append(float(finite.mean()) if finite.size else 0.0)
        p = plane[..., c]
        ramps.append(float(np.nanmax(p) - np.nanmin(p)) if p.size else 0.0)
    return CenteringReport(offset=(offs[0], offs[1]),
                           ramp=(ramps[0], ramps[1]), tol_px=float(tol_px))


def resolve_reference(shifts: np.ndarray, *, center_mode: str,
                      corner_fraction: float = DEFAULT_CORNER_FRACTION,
                      center_xy=None, vacuum_shifts: np.ndarray | None = None,
                      sig_shape: tuple[int, int] | None = None,
                      strict: bool = True) -> np.ndarray | None:
    """Build the descan reference *center_mode* asks for.

    The single place the Center tab's four modes turn into an array, shared by
    :func:`compute_dpc` and the wizard so the two cannot disagree about what
    "corners" means.

    *strict* controls what a missing input does. Scripting (the default) gets a
    ``ValueError`` naming the argument it needs; the wizard passes
    ``strict=False``, because a caret sitting on Manual with no crosshair placed
    yet is mid-interaction, not misconfigured, and "no reference yet" renders
    perfectly well.
    """
    if center_mode not in CENTER_MODES:
        raise ValueError(f"center_mode must be one of {CENTER_MODES}, "
                         f"got {center_mode!r}")
    shifts = np.asarray(shifts, dtype=np.float64)
    if center_mode == "none":
        return None
    if center_mode == "corners":
        return corner_reference(shifts, corner_fraction)
    if center_mode == "manual":
        if center_xy is None or center_xy[0] is None or center_xy[1] is None:
            if strict:
                raise ValueError("center_mode='manual' needs center_xy=(x, y)")
            return None
        if sig_shape is None:
            raise ValueError("center_mode='manual' needs the signal shape")
        return constant_reference(shifts.shape[:2], center_xy, sig_shape)
    if center_mode == "vacuum":
        if vacuum_shifts is None:
            if strict:
                raise ValueError("center_mode='vacuum' needs vacuum_shifts")
            return None
        return vacuum_reference(shifts, vacuum_shifts)
    return None


def _sig_shape(signal) -> tuple[int, int] | None:
    """``(sy, sx)`` of the detector, or ``None`` for a signal without one."""
    try:
        ax = signal.axes_manager.signal_axes
        return (int(ax[1].size), int(ax[0].size))
    except Exception:                                        # pragma: no cover
        return None


def apply_reference(shifts: np.ndarray, reference: np.ndarray | None
                    ) -> np.ndarray:
    """``shifts − reference`` (a ``None`` reference is the identity)."""
    shifts = np.asarray(shifts, dtype=np.float64)
    if reference is None:
        return shifts.copy()
    ref = np.asarray(reference, dtype=np.float64)
    if ref.shape != shifts.shape:
        raise ValueError(f"reference {ref.shape} does not match shifts "
                         f"{shifts.shape}")
    return shifts - ref


