def magnitude_phase_rgb(shifts: np.ndarray, *, rotation: float | None = None,
                        autolim: bool = True, autolim_sigma: float = 4.0,
                        magnitude_limits: tuple[float, float] | None = None,
                        only_phase: bool = False) -> np.ndarray:
    """Beam shifts → an ``(ny, nx, 3)`` uint8 RGB map. Hue = direction, value =
    magnitude.

    This is pyxem's ``BeamShift.get_magnitude_phase_signal`` — called through
    the public method rather than reimplemented, so a SpyDE map is the same
    picture the pyxem examples produce, including the −30° hue offset it applies
    internally. ``add_color_wheel_marker=False``: that marker is a matplotlib
    artist SpyDE cannot render, and its rotation is 90° out anyway (see the
    module docstring) — :func:`color_wheel_rgba` builds the legend instead.

    *only_phase* drops the magnitude weighting so every pixel shows its
    direction at full saturation; useful where the field is weak but ordered.

    Non-finite positions render BLACK rather than poisoning the image. They are
    real and mean "no measurement here": a scan position still streaming in
    during a progressive fill, or one whose beam region captured nothing. Left
    in, a single NaN takes out the whole map, because ``autolim`` derives the
    magnitude limits from a mean and standard deviation.
    """
    bs = as_beam_shift(np.nan_to_num(np.asarray(shifts, dtype=np.float64),
                                     nan=0.0, posinf=0.0, neginf=0.0))
    kw: dict = {"rotation": rotation, "add_color_wheel_marker": False}
    if only_phase:
        s_rgb = bs.get_phase_signal(**kw)
    else:
        s_rgb = bs.get_magnitude_phase_signal(
            autolim=bool(autolim) and magnitude_limits is None,
            autolim_sigma=float(autolim_sigma),
            magnitude_limits=magnitude_limits, **kw)
    s_rgb.change_dtype("uint16")
    arr = np.asarray(s_rgb.data)
    if arr.ndim == 2:                                        # pragma: no cover
        arr = arr[..., None].repeat(3, axis=-1)
    return (arr[..., :3] >> 8).astype(np.uint8)


def magnitude_ceiling(field: np.ndarray, *, autolim_sigma: float = 4.0
                      ) -> float | None:
    """The field magnitude the colour wheel's RIM stands for, in the field's own
    units. The wheel's centre is 0, so this is the other end of its scale.

    :func:`magnitude_phase_rgb` lets pyxem's autolim choose the display ceiling,
    so the only number that cannot disagree with the picture is the one pyxem
    itself computed. This makes the same call on the same array — ``nan_to_num``
    first, exactly as the map does.

    ``None`` if pyxem's helper moves. A legend with no scale on it is a small
    loss; a legend with the WRONG scale on it is a wrong measurement, and it
    would be believed.
    """
    try:
        from pyxem.utils._beam_shift_tools import _get_limits_from_array
    except Exception as e:                                   # pragma: no cover
        log.debug("pyxem's magnitude-limit helper is not importable, so the "
                  "colour wheel goes without a scale: %s", e)
        return None
    try:
        clean = np.nan_to_num(np.asarray(field, dtype=np.float64),
                              nan=0.0, posinf=0.0, neginf=0.0)
        ceiling = float(_get_limits_from_array(
            magnitude(clean), sigma=float(autolim_sigma))[1])
    except Exception as e:                                   # pragma: no cover
        log.debug("deriving the colour-wheel scale failed: %s", e)
        return None
    return ceiling if np.isfinite(ceiling) and ceiling > 0 else None


def color_wheel_rgba(size: int = 192, *, rotation: float | None = None,
                     only_phase: bool = False) -> np.ndarray:
    """The circular phase-direction legend → ``(size, size, 4)`` uint8 RGBA.

    **Generated by the map's own colour rule, not by a copied offset.** The
    wheel is a synthetic beam-shift field in which the shift at each pixel
    points at that pixel's own SCREEN direction from the centre, run through
    :func:`magnitude_phase_rgb` with the same *rotation* as the map. So "find
    this colour on the wheel, read off which way it points" is correct by
    construction, and it stays correct if the colour rule ever changes.

    The screen frame is the displayed image's: ``+x`` right, ``+y`` DOWN (the
    map is drawn ``origin="upper"``). A pixel that sits to the upper-right of the
    wheel centre therefore carries the colour of a shift pointing up and to the
    right in the map.

    Magnitude ramps 0 → 1 from centre to rim, so the legend reads as a key for
    both quantities: black in the middle is zero field, the saturated rim is the
    display maximum. Outside the disc alpha is 0, and the rim is feathered over
    one pixel so it does not alias against the map underneath.
    """
    n = int(max(16, size))
    c = (n - 1) / 2.0
    rows, cols = np.mgrid[0:n, 0:n].astype(np.float64)
    u = (cols - c) / c                     # +right
    v = (rows - c) / c                     # +down  (origin="upper")
    r = np.hypot(u, v)
    # The shift at this pixel points the way the pixel lies: sx = right, sy = down.
    shifts = np.stack([u, v], axis=-1)
    rgb = magnitude_phase_rgb(shifts, rotation=rotation, autolim=False,
                              magnitude_limits=(0.0, 1.0), only_phase=only_phase)
    edge = 2.0 / n
    alpha = np.clip((1.0 - r) / edge, 0.0, 1.0)
    out = np.empty((n, n, 4), dtype=np.uint8)
    out[..., :3] = rgb
    out[..., 3] = (alpha * 255.0).astype(np.uint8)
    return out


def magnitude(shifts: np.ndarray) -> np.ndarray:
    """``|shift|`` per scan point."""
    s = np.asarray(shifts, dtype=np.float64)
    return np.hypot(s[..., 0], s[..., 1])


def phase(shifts: np.ndarray, *, rotation: float | None = None) -> np.ndarray:
    """Direction per scan point in RADIANS on ``[0, 2π)``.

    pyxem's ``arctan2(x, y)`` convention with its −30° display offset applied,
    i.e. the exact angle whose hue :func:`magnitude_phase_rgb` paints, so a
    committed phase map and the RGB map agree.
    """
    s = np.asarray(shifts, dtype=np.float64)
    rot = -30.0 if rotation is None else float(rotation) - 30.0
    return (np.arctan2(s[..., 0], s[..., 1]) + np.deg2rad(rot)) % (2 * np.pi)


