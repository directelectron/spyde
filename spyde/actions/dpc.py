"""
dpc.py — the DPC (differential phase contrast) physics: beam shifts → a field.

Pure compute. No Qt, no IPC, no ``Session`` — so ``spyde.api``, a notebook and
the :mod:`spyde.actions.dpc_action` wizard all run the SAME code (the host
parity contract in ``spyde/actions/README.md``). The interactive wiring lives in
``dpc_action.py``; the figures in ``dpc_display.py``.

The pipeline, in the order the wizard walks it:

1. **Measure** — :func:`measure_beam_shifts` wraps pyxem's
   ``get_direct_beam_position``: one (x, y) beam position per scan point.
2. **Center** — remove the part of that field which is NOT the sample: a
   constant (:func:`constant_reference`), a vacuum scan
   (:func:`vacuum_reference`), or a plane fitted through the four scan corners
   (:func:`corner_reference`). :func:`centering_report` says whether there is
   anything left to remove at all.
3. **Orient** — :func:`rotate_shifts` puts the detector's x/y onto the scan's
   x/y; :func:`estimate_rotation` finds that angle from the data.
4. **Calibrate** — magnetic DPC stops at the deflection; electric DPC goes on
   to MV/cm through :func:`to_electric_field`.
5. **Display** — :func:`magnitude_phase_rgb` and :func:`color_wheel_rgba`.

Two conventions are load-bearing and were both verified against pyxem 0.21
rather than assumed.

**Sign.** ``get_direct_beam_position`` returns ``centre − beam``: the shift you
would APPLY to centre the pattern, i.e. the NEGATIVE of the physical beam
deflection. Every pyxem DPC example (electric_field_dpc, magnetic_dpc) feeds
that value straight into ``get_magnitude_phase_signal`` /
``calibrate_electric_shifts``, so SpyDE does too — a map here matches a
published pyxem figure. ``calibrate_electric_shifts`` divides by ``-e``, which
puts the electric field back the right way round. Do not "fix" the sign here.

**Phase.** pyxem's phase is ``arctan2(shift_x, shift_y)`` — x against y, not the
usual y against x — with a −30° hue offset baked in. The colour wheel therefore
has to be rotated +90° relative to the map for its directions to read true in
the image, which is what ``plot_beam_shift_color`` does (``+60 = −30 + 90``) and
what the marker ``get_magnitude_phase_signal(add_color_wheel_marker=True)``
embeds does NOT (it reuses ``−30``, so it is 90° out and points the wrong way).

:func:`color_wheel_rgba` sidesteps that entirely: instead of porting a magic
offset, it evaluates :func:`magnitude_phase_rgb` — the very function that
colours the map — on a synthetic field of KNOWN screen directions. The legend is
generated by the map's own colour rule, so the two cannot drift apart. See
``test_dpc.py::TestPhaseConvention``.
"""
