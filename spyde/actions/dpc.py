@dataclass
class DpcResult:
    """Everything one DPC run produces, in one object.

    :attr:`field` is the oriented, calibrated field as ``(ny, nx, 2)``; the
    scalar maps are derived views of it. :attr:`units` says what
    :attr:`field` is in — ``MV/cm`` for a calibrated electric run, ``mrad``
    for a calibrated magnetic one, ``px`` when the dataset carried no
    detector calibration.
    """
    field: np.ndarray
    raw_shifts: np.ndarray
    reference: np.ndarray | None
    units: str
    mode: str
    rotation: float
    flip: bool
    reverse: bool
    rgb: np.ndarray
    wheel: np.ndarray
    centering: CenteringReport | None = None
    estimate: RotationEstimate | None = None
    params: dict = _dc_field(default_factory=dict)
    #: Set by ``spyde.api.dpc_map`` / the wizard's Commit — the same record
    #: shape ``commit._stamp_provenance`` writes.
    provenance: dict | None = None

    @property
    def fx(self) -> np.ndarray:
        """The x (horizontal / scan-column) component."""
        return self.field[..., 0]

    @property
    def fy(self) -> np.ndarray:
        """The y (vertical / scan-row) component."""
        return self.field[..., 1]

    @property
    def magnitude(self) -> np.ndarray:
        return magnitude(self.field)

    @property
    def phase(self) -> np.ndarray:
        return phase(self.field, rotation=DISPLAY_ROTATION)

    @property
    def divergence(self) -> np.ndarray:
        """``∇·F`` — charge density, up to a constant, for an electric field."""
        return _div_curl(self.field[..., 0], self.field[..., 1])[0]

    @property
    def curl(self) -> np.ndarray:
        """``(∇×F)_z`` — should be ~0 for a well-oriented electric field."""
        return _div_curl(self.field[..., 0], self.field[..., 1])[1]

    def component(self, name: str) -> np.ndarray:
        return {"fx": self.fx, "fy": self.fy, "magnitude": self.magnitude,
                "phase": self.phase, "divergence": self.divergence,
                "curl": self.curl}[name]


#: Scalar maps a DPC result can show, in the order the view chips list them.
COMPONENTS: tuple[str, ...] = ("fx", "fy", "magnitude", "phase", "divergence",
                               "curl")


def component_titles(mode: str, units: str) -> dict[str, str]:
    """Human labels for :data:`COMPONENTS`, named for the physics being mapped."""
    sym = "E" if mode == "electric" else "B"
    return {
        "fx": f"{sym}x ({units})", "fy": f"{sym}y ({units})",
        "magnitude": f"|{sym}| ({units})", "phase": "Direction (rad)",
        "divergence": "Divergence", "curl": "Curl",
    }
def compute_dpc(signal, *, mode: str = "magnetic",
                method: str = "center_of_mass", half_square_width: int = 0,
                center_mode: str = "corners",
                corner_fraction: float = DEFAULT_CORNER_FRACTION,
                center_xy: tuple[float, float] | None = None,
                vacuum_shifts: np.ndarray | None = None,
                rotation: float | None = None, flip: bool = False,
                reverse: bool = False, auto_rotation: bool = False,
                thickness_nm: float | None = None,
                beam_energy_kev: float | None = None,
                mrad_per_px: float | None = None,
                autolim_sigma: float = 4.0,
                region: "BeamRegion | None" = None,
                shifts: np.ndarray | None = None,
                reference: np.ndarray | None = _UNSET) -> DpcResult:
    """Run the whole DPC pipeline on *signal* and return a :class:`DpcResult`.

    The one entry point shared by ``spyde.api.dpc_map`` and the wizard's Run
    stage, so a scripted result and a clicked one cannot diverge. Pass
    pre-measured *shifts* to skip step 1 (the wizard does, because it measures
    once and then re-orients interactively).

    Pass an explicit *reference* to skip step 2's derivation as well. The wizard
    does that too, and not just for speed: its Center tab can sit in a mode whose
    reference is not determined YET (Manual before a crosshair has been placed,
    Vacuum before a dataset has been chosen). Deriving from *center_mode* alone
    would have to raise there, in the middle of an interaction where "no
    reference yet" is the honest and perfectly usable state. A caller who does
    supply *center_mode* without a reference is scripting, not interacting, and
    a missing input IS an error for them.
    """
    if mode not in FIELD_MODES:
        raise ValueError(f"mode must be one of {FIELD_MODES}, got {mode!r}")
    if center_mode not in CENTER_MODES:
        raise ValueError(f"center_mode must be one of {CENTER_MODES}, "
                         f"got {center_mode!r}")
    raw = (np.asarray(shifts, np.float64) if shifts is not None
           else measure_beam_shifts(signal, method=method,
                                    half_square_width=half_square_width,
                                    region=region))
    report = centering_report(raw)

    # A region dragged onto the beam already says where the beam is, so Manual
    # needs no separate pick — the region's centre IS the reference. This is the
    # whole point of one shape doing both jobs.
    if (center_mode == "manual" and center_xy is None
            and region is not None and region.active):
        center_xy = region.center
    # `is _UNSET`, not `is None` — an explicit `reference=None` means "the
    # caller has decided there is no reference", which is exactly the wizard's
    # not-picked-yet state and must NOT fall back to deriving one.
    if reference is _UNSET:
        reference = resolve_reference(
            raw, center_mode=center_mode, corner_fraction=corner_fraction,
            center_xy=center_xy, vacuum_shifts=vacuum_shifts,
            sig_shape=_sig_shape(signal))
    centered = apply_reference(raw, reference)

    nav_scale = _nav_scale(signal)
    estimate = None
    if auto_rotation or rotation is None:
        estimate = estimate_rotation(centered, mode=mode, nav_scale=nav_scale)
        if rotation is None:
            rotation, flip = estimate.angle, estimate.flip
    oriented = rotate_shifts(centered, float(rotation), flip=flip,
                             reverse=reverse)

    units, calibrated = "px", False
    field = oriented
    scale = mrad_per_px if mrad_per_px is not None else mrad_per_pixel(signal)
    if mode == "electric":
        energy = (beam_energy_kev if beam_energy_kev is not None
                  else beam_energy_kv(signal))
        if scale and thickness_nm and energy:
            field = to_electric_field(oriented, mrad_per_px=scale,
                                      thickness_nm=thickness_nm,
                                      beam_energy_kev=energy, like=signal)
            units, calibrated = "MV/cm", True
    elif scale:
        field, units, calibrated = oriented * float(scale), "mrad", True

    # One display rotation for the map AND its legend — see DISPLAY_ROTATION.
    return DpcResult(
        field=field, raw_shifts=raw, reference=reference, units=units,
        mode=mode, rotation=float(rotation), flip=bool(flip),
        reverse=bool(reverse),
        rgb=magnitude_phase_rgb(field, rotation=DISPLAY_ROTATION,
                                autolim_sigma=autolim_sigma),
        wheel=color_wheel_rgba(rotation=DISPLAY_ROTATION),
        centering=report, estimate=estimate,
        params={"method": method, "half_square_width": int(half_square_width),
                "center_mode": center_mode, "corner_fraction": corner_fraction,
                "thickness_nm": thickness_nm, "beam_energy_kev": beam_energy_kev,
                "mrad_per_px": scale, "calibrated": calibrated,
                # Recorded because it sets the RGB's display ceiling, which is
                # what the colour wheel's rim stands for. Without it the result
                # cannot say what its own picture is scaled to.
                "autolim_sigma": float(autolim_sigma),
                "beam_region": (region.as_dict() if region is not None
                                else BeamRegion().as_dict())},
    )


def _nav_scale(signal) -> tuple[float, float]:
    """``(dy, dx)`` navigation step, defaulting to 1 where uncalibrated."""
    try:
        nav = signal.axes_manager.navigation_axes
        dx = float(nav[0].scale) if len(nav) > 0 else 1.0
        dy = float(nav[1].scale) if len(nav) > 1 else 1.0
        return (dy or 1.0, dx or 1.0)
    except Exception:                                        # pragma: no cover
        return (1.0, 1.0)
