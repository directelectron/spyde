def beam_energy_kv(signal) -> float | None:
    """Accelerating voltage in kV from the signal's metadata, or ``None``."""
    for getter in (
        lambda: signal.calibration.beam_energy,
        lambda: signal.metadata.Acquisition_instrument.TEM.beam_energy,
        lambda: signal.beam_energy,
    ):
        try:
            v = getter()
        except Exception:
            continue
        if v is not None and np.isfinite(float(v)) and float(v) > 0:
            return float(v)
    return None


def _wavelength_nm(beam_energy_kev: float) -> float:
    """Relativistic electron wavelength in nm."""
    from scipy.constants import c, e, h, m_e
    v = float(beam_energy_kev) * 1e3
    return (h / np.sqrt(2 * m_e * e * v * (1 + e * v / (2 * m_e * c ** 2)))) * 1e9


def mrad_per_pixel(signal) -> float | None:
    """Detector scale in mrad/pixel, or ``None`` if the data isn't calibrated.

    Accepts axes already in mrad, or reciprocal axes (nm⁻¹ / Å⁻¹) which are
    converted through ``θ = k·λ`` — the same relation pyxem's
    ``calibration.convert_signal_units("mrad")`` uses, done here directly so it
    also works on a signal whose ``calibration`` object was never set up.
    """
    try:
        ax = signal.axes_manager.signal_axes[0]
        scale, units = float(ax.scale), str(ax.units or "").strip()
    except Exception:                                        # pragma: no cover
        return None
    if not np.isfinite(scale) or scale <= 0:
        return None
    u = units.lower().replace(" ", "")
    if u in ("mrad", "milliradian", "milliradians"):
        return scale
    if u in ("rad", "radian", "radians"):
        return scale * 1e3
    energy = beam_energy_kv(signal)
    if energy is None:
        return None
    lam_nm = _wavelength_nm(energy)
    if u in ("nm^-1", "1/nm", "nm⁻¹", "nm-1"):
        return scale * lam_nm * 1e3
    if u in ("a^-1", "1/a", "å^-1", "1/å", "å⁻¹", "a-1", "angstrom^-1"):
        return scale * 10.0 * lam_nm * 1e3          # Å⁻¹ → nm⁻¹ is ×10
    return None


def to_electric_field(shifts_px: np.ndarray, *, mrad_per_px: float,
                      thickness_nm: float, beam_energy_kev: float,
                      like=None) -> np.ndarray:
    """Beam shifts in pixels → electric field in MV/cm.

    Delegates the physics to pyxem's ``calibrate_electric_shifts`` (the relation
    ``E = m₀·γ·|v|²·θ / (e·t)`` from the electric-field example) rather than
    re-deriving it, so the numbers match the reference workflow. All this adds
    is the pixels→mrad step, which pyxem normally reaches through a fully
    configured ``calibration`` object — doing it explicitly means an
    uncalibrated dataset still works once the user supplies the scale.
    """
    if not np.isfinite(mrad_per_px) or mrad_per_px <= 0:
        raise ValueError("mrad_per_px must be a positive, finite number")
    if not np.isfinite(thickness_nm) or thickness_nm <= 0:
        raise ValueError("thickness must be a positive number of nanometres")
    if not np.isfinite(beam_energy_kev) or beam_energy_kev <= 0:
        raise ValueError("beam energy must be a positive number of kV")
    bs = as_beam_shift(np.asarray(shifts_px, np.float64) * float(mrad_per_px),
                       like=like, units="mrad")
    bs.units = ["mrad", "mrad"]
    bs.beam_energy = float(beam_energy_kev)
    return np.asarray(bs.calibrate_electric_shifts(
        thickness=float(thickness_nm)).data, dtype=np.float64)


#: Display unit for each field mode, given the calibration that was available.
def field_units(mode: str, calibrated: bool) -> str:
    if mode == "electric":
        return "MV/cm" if calibrated else "px"
    return "mrad" if calibrated else "px"


