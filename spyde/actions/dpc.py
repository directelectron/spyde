#: Shapes the beam region can take. ``off`` searches the whole frame.
BEAM_SHAPES: tuple[str, ...] = ("circle", "ring")


@dataclass
class BeamRegion:
    """Where the direct beam is, as a shape the user drags onto it.

    It answers BOTH questions the Center step asks, which is why it is one
    object and one widget rather than two:

    * **which pixels the centre of mass integrates** (:meth:`mask`) — a
      diffracted disc inside the search area pulls the centroid towards itself,
      and on a strongly diffracting sample that drag is larger than the field
      being measured;
    * **where the undeflected beam is** (:attr:`center`) — the constant the
      Manual reference subtracts.

    ``ring`` exists for a beam-stopped or saturated direct beam: the core
    carries no usable intensity gradient (or none at all), so the centroid is
    taken over an annulus that captures the disc EDGE instead. The edge is
    symmetric about the true centre, so its centroid is still the beam position.

    Geometry is IMAGE PIXELS on the detector — the frame anyplotlib's 2-D
    widgets report and the frame ``measure_beam_shifts`` works in. Do not add a
    scale conversion.
    """
    shape: str = "circle"
    cx: float = 0.0
    cy: float = 0.0
    r: float = 0.0
    r_inner: float = 0.0

    @property
    def center(self) -> tuple[float, float]:
        return (float(self.cx), float(self.cy))

    @property
    def active(self) -> bool:
        """Whether this region can actually be integrated over.

        There is no "off" shape — the region is always on the pattern. What this
        still guards is the moment BEFORE a radius exists: a sensible default is
        a fraction of the detector, whose size is unknown until a dataset is
        open, so a freshly constructed region carries ``r = 0`` until
        :func:`default_beam_region` fills it in.
        """
        return self.shape in BEAM_SHAPES and self.r > 0

    def mask(self, sig_shape: tuple[int, int]) -> np.ndarray | None:
        """Boolean keep-mask over the detector, or ``None`` when inactive."""
        if not self.active:
            return None
        sy, sx = int(sig_shape[0]), int(sig_shape[1])
        yy, xx = np.mgrid[0:sy, 0:sx]
        rr = np.hypot(xx - float(self.cx), yy - float(self.cy))
        keep = rr <= float(self.r)
        if self.shape == "ring":
            keep &= rr >= float(self.r_inner)
        return keep

    def contains(self, x: float, y: float) -> bool:
        """Is this detector position inside the region? (Always True when off.)"""
        if not self.active:
            return True
        rr = float(np.hypot(float(x) - self.cx, float(y) - self.cy))
        if rr > float(self.r):
            return False
        return self.shape != "ring" or rr >= float(self.r_inner)

    def as_dict(self) -> dict:
        return {"shape": self.shape, "cx": float(self.cx), "cy": float(self.cy),
                "r": float(self.r), "r_inner": float(self.r_inner)}

    @classmethod
    def from_dict(cls, d: dict | None) -> "BeamRegion":
        d = d or {}
        shape = str(d.get("shape", "off"))
        return cls(shape=shape if shape in BEAM_SHAPES else "circle",
                   cx=float(d.get("cx") or 0.0), cy=float(d.get("cy") or 0.0),
                   r=float(d.get("r") or 0.0),
                   r_inner=float(d.get("r_inner") or 0.0))


def default_beam_region(sig_shape: tuple[int, int], shape: str = "circle"
                        ) -> BeamRegion:
    """The LARGEST region that fits on the detector — the inscribed circle.

    The region is always on the pattern, so its default is what every scan is
    measured with until someone drags it. That makes "generous" a correctness
    requirement, not a nicety: a region that CLIPS the beam pulls the centroid
    back towards its own centre and under-reads the shift. Measured on the
    synthetic disc, with the region centred on the frame:

    ======================  ==========================================
    radius                  error on a true shift of 1.5 / 3.0 / 4.5 px
    ======================  ==========================================
    ``0.25 * min(sy, sx)``  −0.30 / −1.00 / −1.76 px
    ``0.375 * min(sy, sx)`` −0.00 / −0.00 / −0.02 px
    ``0.5 * min(sy, sx)``   0 / 0 / 0
    ======================  ==========================================

    So a quarter-frame default — chosen when the region opened OFF and only
    ever appeared because someone asked for it — silently under-reads every
    field by up to 40%. The inscribed circle reproduces the whole-frame answer
    exactly, and shrinking it onto the beam (which is what excludes the
    first-order discs) is then a deliberate act with a readout to judge it by.
    """
    sy, sx = int(sig_shape[0]), int(sig_shape[1])
    r = max(2.0, 0.5 * min(sy, sx))
    return BeamRegion(shape=shape, cx=sx / 2.0, cy=sy / 2.0, r=r,
                      r_inner=r * 0.35)


def _com_shift_frame(frame, keep, cx0: float, cy0: float):
    """One frame's ``centre − beam`` shift, over the kept pixels.

    Deliberately the same arithmetic as pyxem's ``center_of_mass_from_image``
    (multiply by the mask, then ``ndi.center_of_mass``, then x/y order), so a
    circular region here and pyxem's own ``mask=(x, y, r)`` agree exactly —
    ``test_dpc.py::TestBeamRegion`` asserts that rather than trusting it.
    """
    from scipy import ndimage as ndi
    z = np.asarray(frame, dtype=np.float64)
    if keep is not None:
        z = z * keep
    total = z.sum()
    if not np.isfinite(total) or total <= 0:
        # Nothing inside the region — a NaN says "no measurement here" and
        # propagates visibly, where a silent 0 would read as a centred beam.
        return np.array([np.nan, np.nan], dtype=np.float64)
    com_y, com_x = ndi.center_of_mass(z)
    return np.array([cx0 - com_x, cy0 - com_y], dtype=np.float64)


def _region_weights(keep, sig_shape: tuple[int, int]) -> np.ndarray:
    """``(3, sy, sx)`` float64: the mask, and the mask weighted by x and by y.

    STACKED, so the centre of mass is one contraction over the data rather than
    three. All three quantities read the same block, and a block is the big
    thing — three separate ``einsum`` calls read it three times, which measured
    73 ms against 38 ms for the stacked form on a 64x64x64x64 scan.

    Built ONCE per pass, never per frame. They are detector-sized (a few hundred
    KB at most), while the data they weight is the whole scan.
    """
    sy, sx = int(sig_shape[0]), int(sig_shape[1])
    mask = (np.ones((sy, sx), dtype=np.float64) if keep is None
            else np.asarray(keep, dtype=np.float64))
    yy, xx = np.mgrid[0:sy, 0:sx].astype(np.float64)
    return np.stack([mask, mask * xx, mask * yy])


def _com_shift_blocks(block, weights, cx0: float, cy0: float) -> np.ndarray:
    """Every frame in a block's ``centre − beam`` shift → ``(..., 2)``.

    The vectorised twin of :func:`_com_shift_frame`, and the one production
    uses. Same arithmetic, same result — ``test_dpc.py`` asserts they agree
    element for element — but as three ``einsum`` contractions over the whole
    block instead of a Python call per frame with a ``scipy`` call inside it.
    A scan is tens of thousands of frames, so per-frame overhead IS the runtime;
    this is the same shape ``virtual_image`` reduces with, for the same reason.

    ``einsum`` also accumulates IN PLACE against detector-sized weights, so a
    block's only intermediates are the nav-sized outputs. Casting the block to
    float64 first would allocate four times the chunk on uint16 data — the
    "spills GiBs" pathology virtual_image documents.

    Do NOT pass ``optimize=True``: it plans a contraction that materialises an
    intermediate and measured 136 ms against 38 ms for the plain call.
    """
    moments = np.einsum("...ij,kij->...k", block, weights)
    total = moments[..., 0]
    # Nothing inside the region — a NaN says "no measurement here" and
    # propagates visibly, where a silent 0 would read as a centred beam.
    empty = ~np.isfinite(total) | (total <= 0)
    with np.errstate(invalid="ignore", divide="ignore"):
        out = np.stack([cx0 - moments[..., 1] / total,
                        cy0 - moments[..., 2] / total], axis=-1)
    out[empty] = np.nan
    return out


def private_view(signal):
    """A signal object the caller owns exclusively, over the SAME data buffer.

    hyperspy mutates the signal a method is called on. ``map`` — which every
    measure here goes through — reaches ``_deepcopy_with_new_data``, and that
    helper sets ``self.data = None`` on the LIVE object before deep-copying the
    wrapper, restoring it in a ``finally``. hyperspy's data setter turns that
    ``None`` into a length-1 OBJECT array, so for the width of the copy the
    signal publicly has ``data.shape == (1,)`` (``learning_results``, ``_plot``
    and the models dict are unset over the same window).

    Two threads calling ``map`` on ONE signal therefore race: the second reads
    the first's placeholder and dies with ``ValueError: Chunks do not add up to
    shape. Got chunks=((3, 3, -1, -1),), shape=(1,)``. It is a genuine race, not
    a rare one — it reproduces on a 4-core runner and hides on a many-core box,
    because the interleaving is what changes, not the code.

    **A superseded measure is CANCELLED, not left to finish** — see
    ``DpcWizard._cancel_measure``, which follows the same contract as
    ``virtual_image`` (cancel the prior future, unregister it, register the new
    one so closing the tree stops it). This view is not a licence to let stale
    passes run; it exists because cancellation cannot be instantaneous. A queued
    future cancels cleanly, but one already inside ``map`` runs to its end
    (``ComputeBackend.submit_graph`` documents the same contract), so the new
    pass can still overlap the tail of the old one. It also keeps the worker's
    ``set_signal_type`` off the tree's signal.

    Only the wrapper is duplicated — ``data`` is the same object, not a copy —
    so this stays cheap on a multi-GB lazy scan.

    Call it on the DISPATCH thread, before handing the result to a worker: the
    copy is itself a ``_deepcopy_with_new_data``, so it must not overlap another
    operation on the signal it is copying.
    """
    try:
        return signal._deepcopy_with_new_data(signal.data)
    except Exception as e:
        # Worse to refuse to measure than to measure on the shared object.
        log.debug("private signal view failed (%s); using the live signal", e)
        return signal


def beam_shift_graph(signal, *, method: str = "center_of_mass",
                     half_square_width: int = 0,
                     region: "BeamRegion | None" = None):
    """The LAZY ``(ny, nx, 2)`` beam-shift array, or ``None`` on eager data.

    Split out from :func:`measure_beam_shifts` so an interactive caller can hand
    the graph to ``client.compute`` and hold a CANCELLABLE future, instead of
    blocking on a pass a newer beam region has already superseded.
    The nav chunking is preserved end to end (no rechunk layer), which is what
    makes per-nav-chunk streaming line up with the storage — see Live-Display §1
    in CLAUDE.md and ``test_dpc.py::TestLazy``.
    """
    if not getattr(signal, "_lazy", False):
        return None
    try:
        signal.set_signal_type("electron_diffraction")
    except Exception as e:                                   # pragma: no cover
        log.debug("set_signal_type(electron_diffraction) failed: %s", e)
    if region is not None and region.active and str(method) == "center_of_mass":
        import dask.array as da
        sy, sx = _sig_shape(signal)
        data = signal.data
        weights = _region_weights(region.mask((sy, sx)), (sy, sx))
        # map_blocks, not hyperspy `map`: one vectorised contraction per chunk
        # rather than a Python call per frame. The nav chunking is preserved
        # (no rechunk layer), which is what keeps per-nav-chunk streaming lined
        # up with the storage — Live-Display §1.
        return da.map_blocks(
            _com_shift_blocks, data, weights=weights,
            cx0=sx / 2.0, cy0=sy / 2.0, dtype=np.float64,
            drop_axis=(data.ndim - 2, data.ndim - 1),
            new_axis=data.ndim - 2,
            chunks=data.chunks[:-2] + ((2,),),
            # Declared, not probed: without it dask calls the kernel an extra
            # time on a zero-sized block just to learn the output type.
            meta=np.empty((0,) * (data.ndim - 1), dtype=np.float64),
        )
    else:
        kw: dict = {"method": str(method), "lazy_output": True}
        hw = int(half_square_width or 0)
        if hw > 0:
            kw["half_square_width"] = hw
        out = signal.get_direct_beam_position(**kw)
    data = getattr(out, "data", None)
    return data if hasattr(data, "chunks") else None


def measure_beam_shifts(signal, *, method: str = "center_of_mass",
                        half_square_width: int = 0,
                        region: "BeamRegion | None" = None) -> np.ndarray:
    """Direct-beam position per scan point → ``(ny, nx, 2)`` float64, ``[x, y]``.

    pyxem's convention throughout: the value is ``centre − beam`` in detector
    PIXELS, ``[..., 0]`` horizontal (column) and ``[..., 1]`` vertical (row).

    *region* restricts the centre of mass to a disc or annulus the user has
    dragged onto the beam. pyxem's own ``mask=(x, y, r)`` covers the disc but
    rejects an array mask, so BOTH shapes go through :func:`_com_shift_frame`
    here — one code path, proven equal to pyxem's for the disc case, rather than
    two that could drift.

    *half_square_width* is pyxem's centred square, kept for the methods a region
    does not apply to (0 = whole frame; the kwarg is omitted rather than passed
    as 0, which pyxem reads as an empty window). A *region* supersedes it.

    This is a REDUCTION over the dataset, not a materialisation: a lazy signal
    streams through ``map`` and only the ``(ny, nx, 2)`` result is computed —
    the memory-safety rule in CLAUDE.md is respected.

    """
    try:
        signal.set_signal_type("electron_diffraction")
    except Exception as e:                                   # pragma: no cover
        log.debug("set_signal_type(electron_diffraction) failed: %s", e)

    if region is not None and region.active and str(method) == "center_of_mass":
        sig_shape = _sig_shape(signal)
        sy, sx = sig_shape
        weights = _region_weights(region.mask(sig_shape), sig_shape)
        # Straight through the vectorised path — hyperspy's `map` would add a
        # Python call per frame around arithmetic that is already one einsum
        # over the whole array.
        #
        # A LAZY signal goes through `beam_shift_graph` rather than contracting
        # the dask array here: this kernel's subscript is a per-BLOCK one, and
        # dask's own einsum does not reproduce it. One code path for lazy data,
        # and this function's contract stays a materialised (ny, nx, 2).
        graph = beam_shift_graph(signal, method=method,
                                 half_square_width=half_square_width,
                                 region=region)
        if graph is not None:
            return np.asarray(graph.compute(), dtype=np.float64)
        return _com_shift_blocks(signal.data, weights, sx / 2.0, sy / 2.0)
    else:
        kw: dict = {"method": str(method), "lazy_output": False}
        hw = int(half_square_width or 0)
        if hw > 0:
            kw["half_square_width"] = hw
        shifts = signal.get_direct_beam_position(**kw)
    if getattr(shifts, "_lazy", False):
        shifts.compute()
    return np.asarray(shifts.data, dtype=np.float64)


def region_brightness(signal, region: "BeamRegion | None", *, index=(0, 0)
                      ) -> float:
    """How many times brighter *region* is than the frame average — the live
    "am I on the beam?" readout while dragging.

    NOT the fraction of intensity captured, which was the obvious first choice
    and is unusable: that fraction depends on how much OTHER intensity the
    pattern carries, so a correctly-placed circle reads 0.7 on a weakly
    diffracting sample and 0.2 on a strongly diffracting one, and no single
    threshold means anything. Intensity DENSITY relative to the frame is
    scale-free: on the direct beam it is many times 1, off it is below 1.

    One frame, so it stays cheap enough to recompute on every drag settle. The
    authoritative check is :func:`beam_inside_region` after a real measure.
    """
    if region is None or not region.active:
        return float("inf")
    try:
        frame = np.asarray(signal.inav[int(index[1]), int(index[0])].data,
                           dtype=np.float64)
        keep = region.mask(frame.shape)
        n_in = int(keep.sum())
        if n_in == 0:
            return 0.0
        frame_mean = float(np.nanmean(frame))
        if not np.isfinite(frame_mean) or frame_mean <= 0:
            return 0.0
        return float(np.nansum(frame * keep) / n_in / frame_mean)
    except Exception as e:                                   # pragma: no cover
        log.debug("region brightness probe failed: %s", e)
        return float("inf")


#: A region dimmer than this multiple of the frame average is not on the beam.
#: 1.0 is "no brighter than average detector", which the direct beam never is.
BEAM_DIM_THRESHOLD = 1.0


def beam_inside_region(shifts: np.ndarray, region: "BeamRegion | None",
                       sig_shape: tuple[int, int]) -> bool:
    """Did the beam the measurement FOUND land inside the region?

    **This cannot catch a slipped CIRCLE, and it is important to know why.** The
    centroid of a non-negative distribution restricted to a CONVEX set always
    lies inside that set — so a disc anywhere on the detector trivially
    "contains" its own centroid, whether or not the beam is in it. Only a RING
    can fail this check, by putting the centroid in its hole, which is a real
    and useful signal that the ring is not concentric with the beam.

    For the "is it on the beam at all?" question use :func:`region_brightness`;
    the two together are what :func:`spyde.actions.dpc_action.DpcWizard.
    _warn_if_region_missed` reports on.
    """
    if region is None or not region.active:
        return True
    s = np.asarray(shifts, dtype=np.float64)
    finite = s[np.isfinite(s).all(axis=-1)]
    if finite.size == 0:
        return False
    sy, sx = int(sig_shape[0]), int(sig_shape[1])
    mean_shift = finite.reshape(-1, 2).mean(axis=0)
    # shift = centre - beam, so beam = centre - shift.
    return region.contains(sx / 2.0 - mean_shift[0], sy / 2.0 - mean_shift[1])


def as_beam_shift(shifts: np.ndarray, *, like=None, units: str = "px"):
    """Wrap an ``(ny, nx, 2)`` array back into a pyxem ``BeamShift``.

    Needed wherever pyxem's own physics is the authority (``get_linear_plane``,
    ``calibrate_electric_shifts``, ``get_magnitude_phase_signal``). *like* is an
    optional source signal whose navigation calibration and beam energy are
    copied across.
    """
    import pyxem as pxm
    bs = pxm.signals.BeamShift(np.asarray(shifts, dtype=np.float64))
    bs.units = [units, units]
    if like is not None:
        try:
            src_nav = like.axes_manager.navigation_axes
            for i, ax in enumerate(bs.axes_manager.navigation_axes):
                if i < len(src_nav):
                    ax.scale, ax.offset = src_nav[i].scale, src_nav[i].offset
                    ax.units, ax.name = src_nav[i].units, src_nav[i].name
        except Exception as e:                               # pragma: no cover
            log.debug("copying nav calibration onto BeamShift failed: %s", e)
        try:
            energy = beam_energy_kv(like)
            if energy is not None:
                bs.beam_energy = float(energy)
        except Exception as e:                               # pragma: no cover
            log.debug("copying beam energy onto BeamShift failed: %s", e)
    return bs


